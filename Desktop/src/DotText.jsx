/** 把一行文字排成点阵坐标；返回 { dots:[[x,y]...], width } */
function layoutLine(text) {
  const dots = [];
  let x = 0;
  const chars = [...text.toUpperCase()];
  chars.forEach((ch, i) => {
    const g = GLYPHS[ch] || GLYPHS[' '];
    const w = g[0].length;
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < w; col++) {
        if (g[row][col] === '#') dots.push([x + col, row]);
      }
    }
    x += w + (i < chars.length - 1 ? 1 : 0);
  });
  return { dots, width: x };
}

/**
 * lines：一行或多行文字（多行时逐行居中）。
 * pitch：圆点间距（px），dot：圆点直径（px），gap：行间距（以点为单位）。
 */
export default function DotText({ lines, pitch = 4.6, dot = 3.3, gap = 3, className = '', color = 'currentColor' }) {
  const rows = (Array.isArray(lines) ? lines : [lines]).map(layoutLine);
  const width = Math.max(...rows.map((r) => r.width));
  const height = rows.length * 7 + (rows.length - 1) * gap;
  const r = dot / pitch / 2;
  return (
    <svg
      className={`dot-text ${className}`}
      width={width * pitch}
      height={height * pitch}
      viewBox={`-0.5 -0.5 ${width} ${height}`}
      aria-label={(Array.isArray(lines) ? lines : [lines]).join(' ')}
      role="img"
    >
      {rows.map((row, li) => {
        const ox = (width - row.width) / 2;
        const oy = li * (7 + gap);
        return row.dots.map(([x, y]) => (
          <circle key={`${li}-${x}-${y}`} cx={ox + x} cy={oy + y} r={r} fill={color} />
        ));
      })}
    </svg>
  );
}
